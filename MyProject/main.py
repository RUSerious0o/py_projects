    print("\n" + "=" * 60)
    print_slow("🏀 ГЛАВА 1: ВЕЛИКИЙ КАМБЭК С АЛЕКСАНДРОМ ЧЕРНЫШОВЫМ 🏀")
    print("=" * 60)
    time.sleep(1)
    print_slow("Текущий счёт матча — 🔴 0 : 8 🔴. Ситуация критическая!")
    print_slow("Юра Константинов (#38) врубает режим терминатора и привозит 12 ОЧКОВ!")
    print_slow("Снайпер Александр Чернышов хладнокровно добавляет еще 2 очка!")
    print_slow("Основное время — 🟢 14 : 14 🟢! Юра забивает победный штрафной в серии!")
    print_slow("🏆 ПОБЕДА!")

